let crianca: number = 60;

if (crianca >= 0 && crianca <= 12){

    console.log("Criança");

} else if (crianca >= 13 && crianca <= 17){

    console.log("Adolescente");

}

else if(crianca >= 18 && crianca <= 29){

    console.log("Adulto Jovem");
}

else if(crianca >= 30 && crianca <= 60){

    console.log("Adulto");

}

else{

    console.log("Idade inválida");
}

